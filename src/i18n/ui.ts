export type UiKey = keyof (typeof ui)['en'];

export function t(locale: Locale | string | undefined, key: UiKey, vars?: Record<string, string | number>): string {
	const loc = currentLocale(typeof locale === 'string' ? locale : undefined);
	let text: string = ui[loc][key] ?? ui['zh-CN'][key];
	if (vars) {
		for (const [name, value] of Object.entries(vars)) {
			text = text.replaceAll(`{${name}}`, String(value));
		}
	}
	return text;
}

export function tagLabel(locale: Locale | string | undefined, tag: string): string {
	const key = `tag_${tag.replaceAll(' ', '_')}` as UiKey;
	if (key in ui.en) return t(locale, key);
	return tag;
}

export function clusterLabel(locale: Locale | string | undefined, clusterId: string): string {
	const key = `cluster_${clusterId}` as UiKey;
	if (key in ui.en) return t(locale, key);
	return clusterId;
}
